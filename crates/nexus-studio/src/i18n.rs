/// 0 = en, 1 = zh.
pub fn tr(lang: usize, key: &str) -> &str {
    if lang == 0 {
        return key;
    }
    match ZH.binary_search_by(|(k, _)| (*k).cmp(key)) {
        Ok(i) => ZH[i].1,
        Err(_) => key,
    }
}

/// Translate then substitute {0}, {1}, … with args.
pub fn trf(lang: usize, key: &str, args: &[&str]) -> String {
    let mut s = tr(lang, key).to_string();
    for (i, a) in args.iter().enumerate() {
        s = s.replace(&format!("{{{i}}}"), a);
    }
    s
}

